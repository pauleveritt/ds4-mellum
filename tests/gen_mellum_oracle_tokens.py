"""Write the token files the Mellum forward pass is compared on
(tests/mellum_oracle_compare.sh): three chat-templated prompts rendered by
Mellum 2.1's own chat template and encoded by its own tokenizer, sized to cross
the attention boundaries:

  tests/mellum_oracle_short.tokens   a short system + user turn
  tests/mellum_oracle_1100.tokens    one past the 1,024-token sliding window
  tests/mellum_oracle_2200.tokens    past 2,048 keys, where the full layers'
                                     key splits stop growing

The long user turns are the opening of speed-bench/promessi_sposi.txt (public
domain), cut so the rendered prompt has exactly the target length.  Thinking is
on, so each prompt ends <|im_start|>assistant\\n.

Usage (from the repository root; SNAP holds the model's chat_template.jinja and
tokenizer.json, JetBrains/Mellum2.1-12B-A2.5B-Thinking)::

    uv run --no-project --with jinja2==3.1.6 --with tokenizers==0.23.3 python -I \\
        tests/gen_mellum_oracle_tokens.py $SNAP
"""

import hashlib
import json
import sys

from jinja2.ext import loopcontrols
from jinja2.sandbox import ImmutableSandboxedEnvironment
from tokenizers import Tokenizer

SYSTEM = "You are a helpful assistant."


def main(snap):
    tpl_text = open(snap + "/chat_template.jinja", encoding="utf-8").read()
    env = ImmutableSandboxedEnvironment(trim_blocks=True, lstrip_blocks=True, extensions=[loopcontrols])
    env.filters["tojson"] = lambda x, **kw: json.dumps(x, ensure_ascii=False)
    tpl = env.from_string(tpl_text)
    tok = Tokenizer.from_file(snap + "/tokenizer.json")
    book = open("speed-bench/promessi_sposi.txt", encoding="utf-8").read()

    def render(user):
        msgs = [{"role": "system", "content": SYSTEM}, {"role": "user", "content": user}]
        return tok.encode(tpl.render(messages=msgs, add_generation_prompt=True), add_special_tokens=False).ids

    def exact(target):
        # the longest prefix of the book, in characters, whose rendered prompt fits; then pad with
        # the next characters until the length is exactly the target (one id each at the end)
        lo, hi = 0, len(book)
        while lo < hi:
            mid = (lo + hi + 1) // 2
            if len(render(book[:mid].strip())) <= target:
                lo = mid
            else:
                hi = mid - 1
        ids = render(book[:lo].strip())
        assert len(ids) <= target
        while len(ids) < target:
            lo += 1
            ids = render(book[:lo].strip())
            assert len(ids) <= target + 1
        assert len(ids) == target, (target, len(ids))
        return ids

    tpl_sha = hashlib.sha256(tpl_text.encode()).hexdigest()
    files = [
        ("tests/mellum_oracle_short.tokens", render("Write a haiku about autumn leaves.")),
        ("tests/mellum_oracle_1100.tokens", exact(1100)),
        ("tests/mellum_oracle_2200.tokens", exact(2200)),
    ]
    for path, ids in files:
        with open(path, "w") as f:
            f.write("# Generated by tests/gen_mellum_oracle_tokens.py; do not edit.\n")
            f.write("# %d ids; chat_template.jinja sha256 %s\n" % (len(ids), tpl_sha))
            for i in range(0, len(ids), 16):
                f.write(" ".join(map(str, ids[i:i + 16])) + "\n")
        print("wrote %s: %d ids" % (path, len(ids)))


if __name__ == "__main__":
    main(sys.argv[1])
