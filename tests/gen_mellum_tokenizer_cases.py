"""Write tests/mellum_tokenizer_cases.inc: what Mellum 2.1's own tokenizer does
with a fixed list of strings, for the engine's tokenizer tests to match.

For each string it records the pieces of the snapshot's pre-tokenizer
(Digits(individual_digits) then ByteLevel's GPT-2 expression) and the token
ids of a full encode.  Both are taken in content mode: the added tokens
(<think>, <|im_start|>, ...) are emptied from the spec first, because the
engine's content tokenizer never matches special-token spellings (the chat
renderer pushes those ids itself), and no special tokens are added.

The pieces need no model (tests/test_mellum_tokenizer checks them always);
the ids need the GGUF's vocabulary and merges (checked when
DS4_TEST_MELLUM_MODEL is set).

Usage (from the repository root)::

    uv run --no-project --with tokenizers==0.23.3 python -I \\
        tests/gen_mellum_tokenizer_cases.py --tokenizer $SNAP/tokenizer.json \\
        --out tests/mellum_tokenizer_cases.inc

where $SNAP holds JetBrains/Mellum2.1-12B-A2.5B-Thinking's tokenizer.json.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

# Each string pins a rule of Digits-then-GPT-2, or is ordinary text a host sends.
CASES = [
    ("letter, space, two digits", "a 12"),
    ("call", "foo.bar()"),
    ("two spaces then a letter", "  x"),
    ("contraction", "don't"),
    ("newlines then indent", "\n\n  def"),
    ("combining mark after a letter", "cafe\u0301s"),
    ("superscript two", "\u00b2"),
    ("circled one", "\u2460"),
    ("digits end a stretch: the lookahead sees its end", "  1"),
    ("a whitespace run inside a stretch", "a  \n b"),
    ("contractions are case sensitive", "x'S 're 'RE I've we'll she'd I'm"),
    ("a lone quote", "'"),
    ("tab, newline, space run", " \t\n"),
    ("a digit run is split", "1.5e-30"),
    ("no-break space is whitespace", "\u00a0x"),
    ("em space between letters", "a\u2003b"),
    ("a mark after a space is not a letter", " \u0301a"),
    ("CJK", "\u65e5\u672c\u8a9e text"),
    ("CRLF", "a\r\nb"),
    ("punctuation run takes one leading space", "x ... y"),
    ("a space before a digit stands alone", "x 7"),
    ("emoji and ZWJ", "ok \U0001f469\u200d\U0001f4bb done"),
    ("Python", "def add(a, b):\n    return a + b  # 2024\n"),
    ("JSON tool call", '{"name": "read", "arguments": {"path": "hello.py", "offset": 10}}'),
    ("prose", "The quick brown fox jumps over the lazy dog; it's 3:45pm."),
    ("Cyrillic and Greek", "\u041f\u0440\u0438\u0432\u0435\u0442 \u03ba\u03cc\u03c3\u03bc\u03b5"),
    ("Arabic digits", "\u0661\u0662\u0663 and 456"),
    ("a long space run before code", "x =        1\n\t\tif y:\n"),
    ("shell", "ls -la /tmp && echo \"$HOME\" | wc -c"),
    ("marker spellings are text here", "<filename>main.c<fim_prefix>"),
]


def load_spec(path: Path) -> dict:
    spec = json.loads(Path(path).read_text(encoding="utf-8"))
    spec["added_tokens"] = []
    return spec


def c_string(s: str) -> str:
    out = []
    for b in s.encode("utf-8"):
        if b in (0x22, 0x5C):
            out.append("\\" + chr(b))
        elif 0x20 <= b < 0x7F and chr(b) != "?":
            out.append(chr(b))
        else:
            out.append(f"\\{b:03o}")
    return '"' + "".join(out) + '"'


def render(rows: list[tuple[str, str, list[str], list[int]]], source: str, digest: str) -> str:
    import tokenizers

    out = [
        "/* tests/mellum_tokenizer_cases.inc -- GENERATED by tests/gen_mellum_tokenizer_cases.py;",
        " * never edited by hand.  Mellum 2.1's own tokenizer on each string, in content mode",
        " * (no added tokens, none added): the pre-tokenizer's pieces and the encoded ids.",
        " *",
        f" * tokenizers: {tokenizers.__version__}",
        f" * tokenizer.json: {source} (sha256 {digest})",
        " */",
        "",
    ]
    for i, (_, _, _, ids) in enumerate(rows):
        out.append(f"static const int MELLUM_CASE_IDS_{i}[] = {{{', '.join(map(str, ids))}}};")
    out.append("")
    out.append("static const mellum_tokenizer_case MELLUM_TOKENIZER_CASES[] = {")
    for i, (label, text, pieces, ids) in enumerate(rows):
        plist = ", ".join(c_string(p) for p in pieces)
        out.append(f"    /* {label} */")
        out.append(f"    {{ {c_string(text)}, {len(pieces)}, {{ {plist} }},")
        out.append(f"      MELLUM_CASE_IDS_{i}, {len(ids)} }},")
    out.append("};")
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--tokenizer", required=True, type=Path, help="Mellum 2.1's tokenizer.json")
    ap.add_argument("--out", required=True, type=Path)
    args = ap.parse_args(argv)

    from tokenizers import Tokenizer

    tok = Tokenizer.from_str(json.dumps(load_spec(args.tokenizer)))
    rows = []
    for label, text in CASES:
        pieces = [text[a:b] for _, (a, b) in tok.pre_tokenizer.pre_tokenize_str(text)]
        ids = tok.encode(text, add_special_tokens=False).ids
        assert "".join(pieces) == text, label
        rows.append((label, text, pieces, ids))
    digest = hashlib.sha256(args.tokenizer.read_bytes()).hexdigest()
    source = args.tokenizer.resolve().parent.name
    args.out.write_text(render(rows, source, digest), encoding="utf-8")
    print(f"wrote {args.out}: {len(rows)} cases")
    return 0


if __name__ == "__main__":
    sys.exit(main())
